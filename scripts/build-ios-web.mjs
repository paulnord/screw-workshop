// Dependency-free bundler for this project's named-export-only ES modules.
// Classic scripts avoid file:// ES-module CORS restrictions in WKWebView.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import vm from 'node:vm';
const root=new URL('../',import.meta.url), source=new URL('dist/',root), out=new URL('ios/Web/',root);
await import(new URL('vendor/matter-0.20.0.min.js',source));
const modules=['levels','engine','progress','app'];
let bundle='// Generated by scripts/build-ios-web.mjs. Edit dist/, not this file.\n(()=>{\n"use strict";\n';
for(const name of modules){
 let code=await readFile(new URL(`${name}.mjs`,source),'utf8');
 code=code.replace(/^import\s*\{([^}]+)\}\s*from\s*['"]\.\/(\w+)\.mjs(?:\?[^'"]*)?['"];?$/gm,(_,bindings,dependency)=>{
  if(!modules.slice(0,modules.indexOf(name)).includes(dependency))throw Error(`Unsupported dependency ${dependency}`);
  return `const {${bindings}} = __${dependency};`;
 });
 const names=name==='app'?[]:Object.keys(await import(new URL(`${name}.mjs`,source)));
 code=code.replace(/^export (?=(?:const|function)\s)/gm,'');
 if(/^\s*(import|export)\s/m.test(code))throw Error(`Unsupported module syntax in ${name}; update bundler deliberately.`);
 bundle+=`const __${name}=(()=>{\n${code}\nreturn {${names.join(',')}};\n})();\n`;
}
bundle+='})();\n';new vm.Script(bundle);
let html=await readFile(new URL('index.html',source),'utf8');
html=html.replace(/<script type="module" src="app\.mjs[^"\n]*"><\/script>/,'<script src="game.js"></script>');
html=html.replace('<meta charset="utf-8">','<meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="default-src \'none\'; script-src \'self\'; style-src \'self\' \'unsafe-inline\'; img-src \'self\' data:; connect-src \'none\'; font-src \'none\'; object-src \'none\'; base-uri \'none\'; form-action \'none\'">');
const check=process.argv.includes('--check');
async function emit(file,content){const url=new URL(file,out);if(check){const current=await readFile(url);if(!current.equals(Buffer.from(content)))throw Error(`Stale iOS resource: ${file}. Run node scripts/build-ios-web.mjs`)}else{await mkdir(new URL('.',url),{recursive:true});await writeFile(url,content)}}
await emit('index.html',html);await emit('game.js',bundle);
for(const file of ['style.css','icon.svg','vendor/matter-0.20.0.min.js','vendor/MATTER-LICENSE.txt'])await emit(file,await readFile(new URL(file,source)));
const files=['index.html','game.js','style.css','icon.svg','vendor/matter-0.20.0.min.js','vendor/MATTER-LICENSE.txt'];
const manifest={};for(const file of files)manifest[file]=createHash('sha256').update(await readFile(new URL(file,out))).digest('hex');
await emit('manifest.json',JSON.stringify(manifest,null,2)+'\n');
console.log('Bundled offline iOS game:',fileURLToPath(out));
